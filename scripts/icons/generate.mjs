import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { glyphs } from './glyphs.mjs'

// Generated SVGs stay self-contained for native thumbnail renderers. Browser
// sprites consume the same checked-in files through the existing theme flow.
const directory = new URL('../../resources/icons/scalable/', import.meta.url)
const read = name => readFile(new URL(`${name}.svg`, directory), 'utf8')
const baseBody = svg => svg.match(/<svg\b[^>]*>([\s\S]*)<\/svg>/)[1].trim()
const bases = { file: baseBody(await read('file')), folder: baseBody(await read('folder')) }
const palette = new Map()
for (const filename of await readdir(directory)) {
  if (!filename.endsWith('.svg')) continue
  const svg = await readFile(new URL(filename, directory), 'utf8')
  for (const [, , color, role] of svg.matchAll(/\b(fill|stroke|stop-color)="([^"]+)"\s+data-icon-\1="([^"]+)"/g)) {
    if (palette.has(role) && palette.get(role) !== color) throw new Error(`Conflicting default icon color: ${role}`)
    palette.set(role, color)
  }
}

const fileRoles = { detail: 'ink', panel: 'blue', shade: 'fold', surface: 'paper', sun: 'yellow', terrain: 'green-strong' }
const folderRoles = { detail: 'folder-detail', panel: 'folder', shade: 'folder-inset', surface: 'folder', sun: 'folder-detail', terrain: 'folder-detail' }
const recipes = [
  ['font_file', 'file', 'font'], ['font_folder', 'folder', 'font'],
  ['code_file', 'file', 'code'], ['code_folder', 'folder', 'code'],
  ['document_file', 'file', 'document'], ['document_folder', 'folder', 'document'],
  ['audio_file', 'file', 'music'], ['music_folder', 'folder', 'music'],
  ['picture_file', 'file', 'picture'], ['pictures_folder', 'folder', 'picture'],
  ['video_file', 'file', 'video', { panel: 'purple', shade: 'purple-mid' }], ['video_folder', 'folder', 'video'],
  ['ebook_file', 'file', 'book', { panel: 'green', shade: 'green-mid', surface: 'fold' }], ['books_folder', 'folder', 'book'],
  ['executable_file', 'file', 'gear'], ['config_file', 'file', 'gear'], ['config_folder', 'folder', 'gear'],
  ['package_file', 'file', 'box', { panel: 'orange-strong' }], ['archive_folder', 'folder', 'box'],
  ['temp_folder', 'folder', 'temporary'], ['backup_folder', 'folder', 'backup'],
  ['cache_folder', 'folder', 'cache'], ['games_folder', 'folder', 'games'], ['screenshots_folder', 'folder', 'screenshot'],
]

const check = process.argv.includes('--check')
if (process.argv.slice(2).some(argument => argument !== '--check')) throw new Error('Usage: node scripts/icons/generate.mjs [--check]')
const stale = []
for (const [name, base, glyph, overrides] of recipes) {
  const roles = { ...(base === 'file' ? fileRoles : folderRoles), ...overrides }
  const body = glyphs[glyph].replace(/\b(fill|stroke)="@([a-z-]+)"/g, (_, property, paint) => {
    const role = roles[paint], color = palette.get(role)
    if (!color) throw new Error(`Unknown paint ${paint} for ${name}`)
    return `${property}="${color}" data-icon-${property}="${role}"`
  })
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128" fill="none">\n  <!-- Generated by scripts/icons/generate.mjs; edit shared glyphs there. -->\n  ${bases[base]}\n  <g data-icon-glyph="${glyph}">${body}\n  </g>\n</svg>\n`
  if (check) {
    let actual
    try { actual = await read(name) } catch (error) { if (error.code !== 'ENOENT') throw error }
    if (actual !== svg) stale.push(`${name}.svg`)
  } else {
    await writeFile(new URL(`${name}.svg`, directory), svg)
  }
}
if (stale.length) {
  console.error(`Shared icon SVGs need regeneration: ${stale.join(', ')}\nRun npm --prefix frontend run icons:generate.`)
  process.exitCode = 1
} else {
  console.log(`${check ? 'Verified' : 'Generated'} ${recipes.length} icons from shared glyphs in ${fileURLToPath(directory)}`)
}
